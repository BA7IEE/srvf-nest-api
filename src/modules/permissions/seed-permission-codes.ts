/**
 * 该权限码是否由 seed 定义(即「系统拥有」而非管理员自建)。
 *
 * 目录护栏的唯一谓词:删除 / 创建 / 改码三条写路径都读它,不得各自再判一次。
 */
export function isSeedPermissionCode(code: string): boolean {
  return SEED_PERMISSION_CODE_SET.has(code);
}
