/**
 * seed 事实闭包内全部权限码的**运行时**单一清单 —— 权限目录护栏的判据来源。
 *
 * ──────────────────────────────────────────────────────────────────────────
 * 为什么必须在 `src/` 再放一份(而不是直接读 seed)
 *
 * 权限码的事实源是 seed 事实闭包(`prisma/seed.ts` + `permission-catalog.ts`),
 * 但生产运行时**够不到它**:
 *   1. `tsconfig.json` 的 `include` 只有 `src/**\/*.ts` ⇒ `prisma/seed.ts` 不进 `dist/`;
 *   2. `prisma/seed.ts` 自己 `import { … } from '../src/modules/permissions/permission-catalog'`
 *      ⇒ 若 `src/` 反向 import 它就是**循环依赖**,且会把整个 seed 程序拖进 API 进程。
 * 方向恒为 seed → src,不得反向 —— 所以护栏要判「这个码是不是系统拥有的」,
 * 就只能在 `src/` 侧有一份可在运行时读到的清单。
 *
 * ⚠️ 这确实是**第二份清单**,与本目录 CLAUDE.md「禁止另造代码清单」的默认立场相冲。
 * 它被允许的唯一理由是:**它被机器钉死在事实源上**,漂了当场红 ——
 * 与 [`protected-role-codes.ts`](protected-role-codes.ts)(15 个内置角色的 API 删除保护清单,
 * 靠 seed-rbac e2e 漂移哨兵守)是同一范式的镜像件。没有哨兵的第二份清单才是被禁的那种。
 *
 * ──────────────────────────────────────────────────────────────────────────
 * 谁保证这份清单不漂(三段链,每段各有独立执法位)
 *
 *   本文件  ==(A)==  `RBAC_SEED_CATALOG.permissions` 各桶并集
 *                       ==(B)==  typed-AST 扫出的权限码全集
 *                       ==(C)==  seed 后 DB 里的 `permissions` 行
 *
 *   (A)+(B) [`seed-permission-codes.spec.ts`](seed-permission-codes.spec.ts):
 *           直接跟 `scripts/check-permission-catalog-closure.ts`(红区 selfGuard 内)
 *           算出的 typed-AST **全集**逐条对照,两个方向都查。实质提取逻辑在那个受保护文件里,
 *           本清单改漂 / 提取器口径漂,任一侧动了都会红。
 *   (C)     `test/e2e/seed-permission-catalog-runtime.e2e-spec.ts`:
 *           空库 → 实跑 seed → 读 DB 的 `permissions` 表跟本清单对照。
 *           **这一条是源码侧判据代替不了的** —— 运行时经 API 增删权限行不改任何源码,
 *           源码侧闭包判据(#1129)对那种漂移结构性失明。
 *
 * ──────────────────────────────────────────────────────────────────────────
 * 新增权限码时怎么办
 *
 * 照常改 `prisma/seed.ts` 加数组 + 在 `RBAC_SEED_CATALOG.permissions` 加桶,
 * 然后把新码按字典序补进下面的数组。漏补 ⇒ 上面 (A) 当场红并点名,不会静默。
 *
 * 刻意**不**写「恰 N 条」的冻结断言:那种断言每加一个码都要改数字,
 * 改数字的摩擦会诱导人把数字调大了事;真正的锁是「与事实源逐条相等」。
 */

